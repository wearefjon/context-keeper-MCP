def load_constraints() -> dict[str, Any]:
    _ensure_dirs()
    return _read_json(_context_dir() / "constraints.json")


def load_deprecated_rules() -> dict[str, Any]:
    _ensure_dirs()
    return _read_json(_context_dir() / "deprecated_rules.json")
